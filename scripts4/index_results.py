"""Write results/README.md: which script produced each results file, and when.

There are now enough analysis outputs in ``results/`` that a reader -- including
whoever picks this up next -- cannot tell which script produced which file, nor
whether a file is current or a leftover from an experiment that was superseded.

Generated rather than hand-written, because a hand-written index is exactly the
kind of thing that goes stale silently, and this project has spent a session
finding out what stale-but-plausible costs. The producing script is found by
searching ``scripts4/`` for the filename, so a file with no producer is listed
as an orphan rather than quietly omitted.

Usage: python scripts4/index_results.py
"""

from __future__ import annotations

import datetime as _dt
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
SCRIPTS = ROOT / "scripts4"


def _first_sentence(path: Path) -> str:
    """The opening line of a script's docstring, which is its whole point."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return ""
    m = re.search(r'^\s*(?:"""|\'\'\')(.+)', text, re.M)
    return m.group(1).strip() if m else ""


def main() -> int:
    # Search scripts4/ AND fish4/, and match the STEM as well as the full
    # filename. The first version matched only the full "name.json" inside
    # scripts4/, and called twelve files orphans -- most of which had a perfectly
    # good producer that built its path from a stem, or lived in fish4/. A
    # checker that mislabels working code as dead is worse than no checker,
    # because the next person deletes something.
    # Every Python file in the tree, not an enumerated list of directories.
    # Enumerating them missed scripts/ (the v0.3 tooling) on the second attempt
    # after missing fish4/ on the first, and each miss produced confident false
    # orphans. A checker whose scope is a list someone maintains will drift out
    # of date exactly as silently as the index it is meant to protect.
    sources = sorted(ROOT.rglob("*.py"))
    producers: dict[str, list[str]] = {}
    for src in sources:
        if "__pycache__" in src.parts or ".git" in src.parts:
            continue
        body = src.read_text(encoding="utf-8", errors="replace")
        rel = src.relative_to(ROOT).as_posix()
        for f in RESULTS.glob("*.json"):
            if f.name in body or f.stem in body:
                producers.setdefault(f.name, []).append(rel)

    rows = []
    for f in sorted(RESULTS.glob("*.json")):
        who = producers.get(f.name, [])
        size = f.stat().st_size
        when = _dt.datetime.utcfromtimestamp(f.stat().st_mtime)
        note = ""
        try:
            d = json.loads(f.read_text())
            if isinstance(d, dict) and "_note" in d:
                note = str(d["_note"])[:110]
        except Exception:
            note = "(not valid JSON)"
        rows.append((f.name, who, size, when, note))

    lines = [
        "# What is in `results/`",
        "",
        "Generated by `scripts4/index_results.py`. Do not edit by hand --",
        "regenerate it, so it cannot drift away from what is actually here.",
        "",
        "The producing script is found by searching every `.py` in the tree for",
        "the file's name or stem. A file listed with no producer is an orphan:",
        "nothing in the tree writes it, so it is a leftover rather than a",
        "result. The match is loose on purpose --- a false orphan invites",
        "someone to delete working output.",
        "",
        "| file | written by | size | modified (UTC) |",
        "|---|---|---:|---|",
    ]
    orphans = []
    for name, who, size, when, note in rows:
        w = ", ".join(f"`{x}`" for x in who) if who else "**orphan**"
        if not who:
            orphans.append(name)
        lines.append(f"| `{name}` | {w} | {size:,} | {when:%Y-%m-%d %H:%M} |")
        if note:
            lines.append(f"| | _{note}_ | | |")

    lines += ["", "## What each producer is for", ""]
    seen = set()
    for _, who, _, _, _ in rows:
        for x in who:
            if x in seen:
                continue
            seen.add(x)
            lines.append(f"- **`{x}`** --- {_first_sentence(ROOT / x)}")

    if orphans:
        lines += ["", "## Orphans", "",
                  "Nothing in `scripts4/` writes these. Either the producer was",
                  "renamed, or the file is left over from a superseded run.", ""]
        lines += [f"- `{o}`" for o in orphans]

    dest = RESULTS / "README.md"
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {dest}  ({len(rows)} files, {len(orphans)} orphan(s))")
    for o in orphans:
        print(f"  orphan: {o}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
